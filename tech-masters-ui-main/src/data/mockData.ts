// Price formatter
export const formatPrice = (price: number): string => {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(price);
};

// Calculate GST
export const calculateGST = (subtotal: number, rate: number = 18): number => {
  return Math.round(subtotal * rate / 100);
};
